const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
const {pathToFileURL}=require('node:url');
(async()=>{
 const catalog=JSON.parse(fs.readFileSync('assets/app-changelog.json','utf8')); catalog.currentVersion='1.7.10';catalog.releases.push({version:'99.0.0',publishedAt:null,body:'## <img src=x onerror=window.injected=true>\n\n- **Safe** <script>window.injected=true</script>'});
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try {
  const page=await browser.newPage({viewport:{width:1120,height:780}});
  await page.addInitScript(catalog=>{
   window.installs=0;
   window.__TAURI__={core:{invoke:async command=>{
    if(command==='get_status')return {ready:true,installed:false};
    if(command==='show_main_window')return;
    if(command==='get_app_changelog')return catalog;
    if(command==='check_app_update')return {available:localStorage.getItem('testOfferUpdate')==='yes',currentVersion:'1.7.10',version:'1.7.11'};
    if(command==='install_app_update')window.installs++;
    throw Error(command);
   }}};
  },catalog);
  const url=pathToFileURL(path.resolve('web/index.html')).href;
  await page.goto(url);
  const dialog=page.locator('#app-changelog-dialog');
  await dialog.waitFor({state:'visible'});
  assert.equal(await page.locator('.app-changelog-card h3').textContent(),'Hotori 1.7.10');
  assert.equal(await page.locator('#app-changelog-close').evaluate(el=>el===document.activeElement),true);
  assert.equal(await dialog.evaluate(el=>getComputedStyle(el).scrollbarWidth),'none');
  const picker=page.getByLabel('App release version');
  const layout=await picker.evaluate(el=>{
   const box=el.getBoundingClientRect(),label=el.parentElement.querySelector('span').getBoundingClientRect();
   const style=getComputedStyle(el);
   return {width:box.width,center:box.x+box.width/2,labelCenter:label.x+label.width/2,labelBottom:label.bottom,top:box.top,weight:style.fontWeight,color:style.color,shadow:style.textShadow,blur:style.getPropertyValue('--glass-surface-blur').trim(),refraction:el.style.getPropertyValue('--glass-refraction')};
  });
  assert(layout.width<=280&&Math.abs(layout.center-layout.labelCenter)<1&&layout.labelBottom<layout.top,'Compact dropdown has its label centered above');
  assert.equal(layout.weight,'700'); assert.equal(layout.color,'rgb(255, 255, 255)'); assert.notEqual(layout.shadow,'none');
  assert.equal(layout.blur,'24px'); assert.equal(layout.refraction,'','Version selection must use acrylic without refraction');
  await picker.click();
  await page.waitForFunction(()=>document.querySelector('select:open'));
  const popup=await picker.evaluate(el=>{const s=getComputedStyle(el,'::picker(select)');return {blur:s.backdropFilter,height:parseFloat(s.height),limit:Math.min(320,innerHeight*.5),overflow:s.overflowY};});
  assert.equal(popup.blur,'blur(24px) saturate(1.15)');
  assert(popup.height<=popup.limit+2,'Long release menus stay bounded');
  assert.equal(popup.overflow,'auto');
  await page.keyboard.press('Escape');
  await picker.selectOption('1.9.0');
  assert.equal(await page.locator('.changelog-release-heading h3').textContent(),'Hotori 1.9.0');
  assert.deepEqual(await page.locator('.changelog-section-heading span').allTextContents(),['Theme presets','Clearer release notes','Clearer settings']);
  assert.equal(await page.locator('.changelog-section-heading svg').count(),3);assert.equal(await page.locator('.changelog-bullet').count(),4);
  assert.equal(await page.locator('.app-changelog-card.guide-step').count(),0,'Content is not a single dark acrylic slab');
  const titleMaterial=await page.locator('.changelog-release-heading').evaluate(e=>({blur:getComputedStyle(e).backdropFilter,fill:getComputedStyle(e).backgroundColor,border:getComputedStyle(e).borderLeftWidth}));
  assert.match(titleMaterial.blur,/blur\(24px\)/);assert.match(titleMaterial.fill,/rgba\(255, 255, 255,/);assert.equal(titleMaterial.border,'3px');assert.equal(await page.locator('.changelog-section-heading').first().evaluate(e=>getComputedStyle(e).borderBottomWidth),'0px');
  assert(!(await page.locator('.app-changelog-card').textContent()).includes('revision'));
  await fs.promises.mkdir('target/qa',{recursive:true});await page.waitForTimeout(400);await page.screenshot({path:'target/qa/app-changelog-hierarchy.png'});
  await picker.selectOption('99.0.0');assert.equal(await page.locator('#app-changelog-content img,#app-changelog-content script').count(),0);assert.equal(await page.locator('#app-changelog-content strong').textContent(),'Safe');assert((await page.locator('#app-changelog-content').textContent()).includes('<script>'));assert.equal(await page.evaluate(()=>window.injected),undefined);
  const body=catalog.releases.find(r=>r.version==='1.7.8').body;
  await page.getByLabel('App release version').selectOption('1.7.8');
  assert((await page.locator('.app-changelog-card').textContent()).includes('50%'));
  assert(body.includes('50%'));
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>localStorage.getItem('hotori.appChangelogSeenVersion')==='1.7.10');
  await page.reload(); await page.waitForTimeout(900);
  assert.equal(await dialog.isVisible(),false,'Same version does not reopen');
  await page.getByRole('button',{name:'App Changelog',exact:true}).click();
  await dialog.waitFor({state:'visible'});
  await page.getByLabel('App release version').selectOption('1.0.0');
  assert.equal(await page.locator('.app-changelog-card h3').textContent(),'Hotori 1.0.0');
  await page.setViewportSize({width:560,height:560});
  await page.waitForTimeout(300);
  const box=await dialog.boundingBox();
  assert(box.y>=0&&box.y+box.height<=560);
  await page.locator('#app-changelog-content').evaluate(el=>el.scrollTop=el.scrollHeight);
  await page.screenshot({path:'target/qa/app-changelog-560.png'});
  await page.locator('#app-changelog-close').click();
  await page.evaluate(()=>localStorage.setItem('hotori.appChangelogSeenVersion','1.7.8'));
  await page.evaluate(()=>localStorage.setItem('testOfferUpdate','yes'));
  await page.reload(); await dialog.waitFor({state:'visible'});
  assert.equal(await page.locator('.app-changelog-card h3').textContent(),'Hotori 1.7.10');
  assert.equal(await page.locator('#app-update-dialog').isVisible(),false);
  await page.locator('#app-changelog-close').click();
  await page.locator('#app-update-dialog').waitFor({state:'visible'});
  assert.equal(await page.evaluate(()=>window.installs),0);
  console.log('PASS first/new version prompt, dismiss/relaunch, manual app-only history, current selection, small-window scrolling and no automatic install');
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});
